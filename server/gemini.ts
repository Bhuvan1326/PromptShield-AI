import { GoogleGenAI } from "@google/genai";
import type { Finding, InvestigationResponse, RunRecord } from "../shared/types";
import { getTestCase } from "./engine/fixtures";
import { sanitize } from "./engine/harness";

const TIMEOUT_MS = 12_000;
const MAX_PROMPT_CHARS = 6_000;

export function geminiStatus() {
  const key = process.env.GEMINI_API_KEY;
  const model = process.env.GEMINI_MODEL || "gemini-2.0-flash";
  return {
    configured: Boolean(key && key.trim()),
    model,
    message:
      key && key.trim()
        ? "Gemini configured — AI investigation summaries available."
        : "GEMINI_API_KEY not set. Deterministic testing works fully; set the key in the server .env to enable AI investigation summaries.",
  };
}

export class GeminiUnavailable extends Error {}

export async function investigate(
  run: RunRecord,
  finding: Finding,
): Promise<InvestigationResponse> {
  const status = geminiStatus();
  if (!status.configured) {
    throw new GeminiUnavailable(
      "Gemini is not configured on the server. Set GEMINI_API_KEY in the backend .env and restart.",
    );
  }

  const test = getTestCase(finding.testId);
  const prompt = buildPrompt(run, finding, test?.title ?? finding.testId);

  const ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY! });

  const res = await ai.models.generateContent({
    model: status.model,
    contents: prompt,
    config: {
      abortSignal: AbortSignal.timeout(TIMEOUT_MS),
      temperature: 0.2,
      maxOutputTokens: 700,
    },
  });
  const text = (res.text ?? "").trim();
  if (!text) throw new Error("Gemini returned an empty response.");

  return {
    findingId: finding.id,
    runId: run.id,
    model: status.model,
    generatedAt: new Date().toISOString(),
    explanation: sanitize(text, 4000),
    observedEvidence: finding.evidence
      .filter((e) => e.kind === "canary_check" || e.kind === "action_check")
      .map((e) => `${e.label}: ${e.content}`),
    recommendedMitigations: [finding.remediation],
    uncertainty:
      "This summary was generated by an AI model from sanitized, simulated evidence. It is explanatory only — the deterministic harness verdicts remain authoritative.",
    isAiGenerated: true,
  };
}

function buildPrompt(run: RunRecord, finding: Finding, testTitle: string): string {
  const evidence = finding.evidence
    .map((e) => `- [${e.kind}] ${e.label}: ${e.content}`)
    .join("\n");

  const raw = [
    "You are a security analyst writing a brief, factual explanation of a",
    "finding from a DETERMINISTIC SIMULATION harness (no real systems or data).",
    "Do not invent facts. Do not claim this affects real systems. 150 words max.",
    "",
    `Environment: ${run.environment}`,
    `Scenario: ${testTitle} (${finding.testId})`,
    `Severity: ${finding.severity}`,
    `Observed failure: ${finding.description}`,
    "",
    "Sanitized evidence:",
    evidence,
    "",
    "Explain: what the observed behavior shows, why it would matter if it were",
    "a real assistant, and the key mitigation. Plain text only.",
  ].join("\n");

  return raw.length > MAX_PROMPT_CHARS ? raw.slice(0, MAX_PROMPT_CHARS) : raw;
}
